
use sakila;
-- 1. Retrieve all customers
SELECT first_name, last_name, email
FROM customer;

-- 2. Find all movies with rating 'PG'
SELECT title, rating
FROM film
WHERE rating = 'PG';

-- 3. Count total number of films
SELECT COUNT(*) AS total_films
FROM film;

-- 4. Find customers from London
#1
SELECT c.first_name, c.last_name, ci.city
FROM customer c
JOIN address a ON c.address_id = a.address_id
JOIN city ci ON a.city_id = ci.city_id
WHERE ci.city = 'London';
#2
SELECT c.first_name, c.last_name
FROM customer c
JOIN address a ON c.address_id = a.address_id
JOIN city ci ON a.city_id = ci.city_id
WHERE ci.city = 'London';

#3
SELECT first_name, last_name, city
FROM customer
JOIN address USING(address_id)
JOIN city USING(city_id)
WHERE city = 'London';

-- 5. Show films longer than 120 minutes
SELECT title, length
FROM film
WHERE length > 120;

-- 6. Top 5 rented movies
SELECT f.title, COUNT(r.rental_id) AS rental_count
FROM film f
JOIN inventory i ON f.film_id = i.film_id
JOIN rental r ON i.inventory_id = r.inventory_id
GROUP BY f.title
ORDER BY rental_count DESC
LIMIT 5;
#2
SELECT title, COUNT(*) AS rental_count
FROM film
JOIN inventory USING(film_id)
JOIN rental USING(inventory_id)
GROUP BY title
ORDER BY rental_count DESC
LIMIT 5;

-- 7. Revenue generated by each store
SELECT s.store_id,
       SUM(p.amount) AS total_revenue
FROM store s
JOIN staff st ON s.store_id = st.store_id
JOIN payment p ON st.staff_id = p.staff_id
GROUP BY s.store_id;

#2
SELECT store_id,
       SUM(amount) AS total_revenue
FROM staff
JOIN payment USING(staff_id)
GROUP BY store_id;

-- 8. Customers who rented more than 30 movies
SELECT c.customer_id,
       c.first_name,
       c.last_name,
       COUNT(r.rental_id) AS total_rentals
FROM customer c
JOIN rental r ON c.customer_id = r.customer_id
GROUP BY c.customer_id, c.first_name, c.last_name
HAVING COUNT(r.rental_id) > 30;

#2
SELECT customer_id,
       COUNT(*) AS total_rentals
FROM rental
GROUP BY customer_id
HAVING COUNT(*) > 30;

-- 9. Average rental duration by category
SELECT cat.name AS category,
       AVG(f.rental_duration) AS avg_rental_duration
FROM category cat
JOIN film_category fc ON cat.category_id = fc.category_id
JOIN film f ON fc.film_id = f.film_id
GROUP BY cat.name;

#2
SELECT name AS category,
       AVG(rental_duration) AS avg_rental_duration
FROM category
JOIN film_category USING(category_id)
JOIN film USING(film_id)
GROUP BY name;

-- 10. Find inactive customers
SELECT first_name, last_name
FROM customer
WHERE active = 0;

-- 11. Monthly revenue trend
SELECT DATE_FORMAT(payment_date, '%Y-%m') AS month,
       SUM(amount) AS revenue
FROM payment
GROUP BY month
ORDER BY month;

-- 12. Rank customers based on spending
SELECT customer_id,
       SUM(amount) AS total_spent,
       RANK() OVER (ORDER BY SUM(amount) DESC) AS ranking
FROM payment
GROUP BY customer_id;

-- 13. Find films never rented
SELECT f.title
FROM film f
LEFT JOIN inventory i ON f.film_id = i.film_id
LEFT JOIN rental r ON i.inventory_id = r.inventory_id
WHERE r.rental_id IS NULL;

#2
SELECT title
FROM film
LEFT JOIN inventory USING(film_id)
LEFT JOIN rental USING(inventory_id)
WHERE rental_id IS NULL;

-- 14. Top category by revenue
SELECT c.name AS category,
       SUM(p.amount) AS revenue
FROM category c
JOIN film_category fc ON c.category_id = fc.category_id
JOIN inventory i ON fc.film_id = i.film_id
JOIN rental r ON i.inventory_id = r.inventory_id
JOIN payment p ON r.rental_id = p.rental_id
GROUP BY c.name
ORDER BY revenue DESC
LIMIT 1;

#2
SELECT name AS category,
       SUM(amount) AS revenue
FROM category
JOIN film_category USING(category_id)
JOIN inventory USING(film_id)
JOIN rental USING(inventory_id)
JOIN payment USING(rental_id)
GROUP BY name
ORDER BY revenue DESC
LIMIT 1;

-- 15. Running total revenue
SELECT payment_date,
       amount,
       SUM(amount) OVER (ORDER BY payment_date) AS running_total
FROM payment;

-- 16. Loyal customers
SELECT c.customer_id,
       c.first_name,
       c.last_name,
       COUNT(r.rental_id) AS rentals,
       SUM(p.amount) AS total_spent
FROM customer c
JOIN rental r ON c.customer_id = r.customer_id
JOIN payment p ON r.rental_id = p.rental_id
GROUP BY c.customer_id, c.first_name, c.last_name
ORDER BY total_spent DESC;

#2
SELECT customer_id,
       COUNT(*) AS rentals,
       SUM(amount) AS total_spent
FROM payment
GROUP BY customer_id
ORDER BY total_spent DESC;

-- 17. Peak rental hours
SELECT HOUR(rental_date) AS rental_hour,
       COUNT(*) AS total_rentals
FROM rental
GROUP BY rental_hour
ORDER BY total_rentals DESC;

-- 18. Staff performance analysis
SELECT s.staff_id,
       s.first_name,
       COUNT(p.payment_id) AS transactions,
       SUM(p.amount) AS revenue
FROM staff s
JOIN payment p ON s.staff_id = p.staff_id
GROUP BY s.staff_id, s.first_name;
